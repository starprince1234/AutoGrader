    def create_question(
        self,
        *,
        course_id: uuid.UUID,
        title: str,
        stem_markdown: str,
        language: str,
        status: str,
        tags: Sequence[str],
        created_by: uuid.UUID | None,
        now: datetime,
    ) -> Question:
        question = Question(
            question_id=new_id(),
            course_id=course_id,
            title=title,
            stem_markdown=stem_markdown,
            language=language,
            status=status,
            tags=list(tags),
            created_by=created_by,
            created_at=now,
            updated_at=now,
        )
        self.session.add(question)
        self.session.flush()
        return question

    def get_question(self, question_id: uuid.UUID) -> Question | None:
        return self.session.get(Question, question_id)

    def list_questions(
        self,
        *,
        course_ids: Iterable[uuid.UUID] | None,
        course_id: uuid.UUID | None,
        language: str | None,
        published_only: bool,
        limit: int,
        after: tuple[datetime, uuid.UUID] | None = None,
        tags: Sequence[str] = (),
    ) -> tuple[list[Question], bool]:
        statement = select(Question).where(Question.deleted_at.is_(None))
        if course_ids is not None:
            scoped = list(course_ids)
            if not scoped:
                return [], False
            statement = statement.where(Question.course_id.in_(scoped))
        if course_id is not None:
            statement = statement.where(Question.course_id == course_id)
        if language is not None:
            statement = statement.where(Question.language == language)
        if published_only:
            statement = statement.where(Question.status == "published")
        if tags:
            # All-of, not any-of (CHG-0013). ``jsonb @>`` is exactly containment of the
            # whole requested set, so "processes" AND "paging" narrows the view; a caller
            # who wants the union repeats the request. The GIN index makes it a real
            # retrieval path rather than a filter applied after loading the bank.
            statement = statement.where(Question.tags.contains(list(tags)))
        if after is not None:
            created_at, question_id = after
            statement = statement.where(
                (Question.created_at < created_at)
                | ((Question.created_at == created_at) & (Question.question_id < question_id))
            )
        statement = statement.order_by(Question.created_at.desc(), Question.question_id.desc())
        statement = statement.limit(limit + 1)
        rows = list(self.session.execute(statement).scalars())
        has_more = len(rows) > limit
        return rows[:limit], has_more

    def tag_coverage(
        self,
        *,
        course_ids: Iterable[uuid.UUID] | None,
        course_id: uuid.UUID,
        published_only: bool,
    ) -> tuple[int, int, int, list[tuple[str, int]]]:
        """Counts for the tag-coverage read (``CHG-0020``).

        Returns ``(total, tagged, untagged, tag_counts)``. Two aggregates over the same
        visibility predicate, and the split matters:

        * the totals are one row of ``count(*) FILTER`` clauses, so ``tagged`` and
          ``untagged`` are counted from the rows themselves rather than derived by
          subtraction -- which is what makes ``tagged + untagged == total`` a statement
          about the data instead of about arithmetic done afterwards;
        * the per-tag numbers come from expanding ``tags`` with
          ``jsonb_array_elements_text`` and grouping, so a tag no question carries cannot
          appear at all (``GROUP BY`` only yields groups that exist) and the order is
          fixed here: count descending, then tag ascending.

        Per-tag counts **overlap**: one question may carry up to 20 tags, so their sum
        exceeds ``total`` whenever the bank reuses a topic. That is the declared reading,
        not a defect. There is no pre-aggregated table: a second source of truth would
        have to be maintained, and at one course's worth of questions it would buy
        nothing (``CHG-0020`` §5).
        """
        filters = [Question.deleted_at.is_(None), Question.course_id == course_id]
        if course_ids is not None:
            scoped = list(course_ids)
            if not scoped:
                return 0, 0, 0, []
            filters.append(Question.course_id.in_(scoped))
        if published_only:
            filters.append(Question.status == "published")

        tagged = func.jsonb_array_length(Question.tags) > 0
        untagged = func.jsonb_array_length(Question.tags) == 0
        totals = self.session.execute(
            select(
                func.count().label("total"),
                func.count().filter(tagged).label("tagged"),
                func.count().filter(untagged).label("untagged"),
            ).where(*filters)
        ).one()

        # One column of a set-returning function over the question's own jsonb column:
        # the expansion is what makes "how many questions mention this topic" answerable,
        # and `joins_implicitly` is SQLAlchemy's own way of saying the function belongs in
        # this FROM clause without a join key.
        tag = func.jsonb_array_elements_text(Question.tags).column_valued(joins_implicitly=True)
        per_tag = self.session.execute(
            select(tag, func.count().label("question_count"))
            .select_from(Question)
            .where(*filters)
            .group_by(tag)
            .order_by(func.count().desc(), tag.asc())
        ).all()
        return (
            int(totals.total),
            int(totals.tagged),
            int(totals.untagged),
            [(row[0], int(row[1])) for row in per_tag],
        )

