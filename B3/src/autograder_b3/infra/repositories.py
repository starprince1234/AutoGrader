class ProtectedContentRepository:
    """Protected reads/writes. Requires the internal database role."""

    def __init__(self, session: Session) -> None:
        self.session = session

    # --- blobs and fixtures ----------------------------------------------

    def put_blob(self, content: bytes, *, content_sha256: str, now: datetime) -> Blob:
        statement = (
            pg_insert(Blob)
            .values(
                content_sha256=content_sha256,
                content=content,
                size_bytes=len(content),
                created_at=now,
            )
            .on_conflict_do_nothing(index_elements=[Blob.content_sha256])
        )
        self.session.execute(statement)
        self.session.flush()
        blob = self.session.get(Blob, content_sha256)
        if blob is None:  # pragma: no cover - only reachable on a lost race
            raise RuntimeError("blob insert did not persist")
        return blob

    def upsert_fixture(
        self,
        *,
        question_version_id: uuid.UUID,
        path: str,
        mount: str,
        student_visible: bool = False,
        test_case_id: uuid.UUID | None = None,
        content: bytes,
        content_sha256: str,
        now: datetime,
    ) -> Fixture:
        self.put_blob(content, content_sha256=content_sha256, now=now)
        values = {
            "fixture_id": new_id(),
            "question_version_id": question_version_id,
            "test_case_id": test_case_id,
            "path": path,
            "mount": mount,
            "student_visible": student_visible,
            "content_sha256": content_sha256,
            "size_bytes": len(content),
            "created_at": now,
        }
        if test_case_id is None:
            statement = (
                pg_insert(Fixture)
                .values(**values)
                .on_conflict_do_update(
                    index_elements=[Fixture.question_version_id, Fixture.path, Fixture.mount],
                    index_where=Fixture.test_case_id.is_(None),
                    set_={
                        "student_visible": student_visible,
                        "content_sha256": content_sha256,
                        "size_bytes": len(content),
                    },
                )
            )
        else:
            statement = (
                pg_insert(Fixture)
                .values(**values)
                .on_conflict_do_update(
                    index_elements=[
                        Fixture.question_version_id,
                        Fixture.test_case_id,
                        Fixture.path,
                        Fixture.mount,
                    ],
                    index_where=Fixture.test_case_id.is_not(None),
                    set_={
                        "student_visible": student_visible,
                        "content_sha256": content_sha256,
                        "size_bytes": len(content),
                    },
                )
            )
        self.session.execute(statement)
        self.session.flush()
        return self.get_fixture(question_version_id, path, mount, test_case_id=test_case_id)

