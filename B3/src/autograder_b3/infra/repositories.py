"""Data access for the ``b3`` schema.

Two repositories, matching the two database roles:

* :class:`QuestionBankRepository` - ordinary question-bank reads/writes. Must stay
  usable by the least-privilege role, i.e. it never selects from
  ``reference_answers`` / ``test_cases`` / ``blobs`` / ``test_suites``.
* :class:`ProtectedContentRepository` - reference answers, hidden cases, fixtures
  and their content-addressed blobs. Only the compile/publish path touches it.

Keeping them separate is what makes the privilege boundary checkable: the
acceptance test connects as the ordinary role and asserts that a protected read
fails at the database.
"""

