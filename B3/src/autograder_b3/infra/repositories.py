def new_id() -> uuid.UUID:
    """UUID v4, generated by the owner at creation time and never mutated."""
    return uuid.uuid4()


def _escape_like(value: str) -> str:
    """把 LIKE 的通配符转义成字面量（配合 `ilike(..., escape=...)` 使用）。"""
    return value.replace("\\", "\\\\").replace("%", "\\%").replace("_", "\\_")


