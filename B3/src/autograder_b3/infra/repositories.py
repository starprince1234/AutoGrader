    # --- versions ---------------------------------------------------------

    def next_version_number(self, question_id: uuid.UUID) -> int:
        current = self.session.execute(
            select(func.max(QuestionVersion.version)).where(
                QuestionVersion.question_id == question_id
            )
        ).scalar_one_or_none()
        return int(current or 0) + 1

    def create_version(
        self,
        *,
        question_id: uuid.UUID,
        version: int,
        language: str,
        stem_markdown: str,
        adapter_manifest: dict[str, Any],
        max_files: int,
        max_total_bytes: int,
        created_by: uuid.UUID | None,
        now: datetime,
        revision_diff: dict[str, Any] | None = None,
        revision_note: str | None = None,
    ) -> QuestionVersion:
        """Insert a version. The revision record is computed by the caller.

        ``revision_note`` and ``revision_diff`` are both ``None`` for a version that
        supersedes nothing; the write path decides that, this method only persists it.
        """
        row = QuestionVersion(
            question_version_id=new_id(),
            question_id=question_id,
            version=version,
            status="draft",
            language=language,
            stem_markdown=stem_markdown,
            adapter_manifest=adapter_manifest,
            content_digest=None,
            package_digest=None,
            max_files=max_files,
            max_total_bytes=max_total_bytes,
            revision_note=revision_note,
            revision_diff=revision_diff,
            created_by=created_by,
            created_at=now,
            updated_at=now,
            published_at=None,
            archived_at=None,
        )
        self.session.add(row)
        self.session.flush()
        return row

