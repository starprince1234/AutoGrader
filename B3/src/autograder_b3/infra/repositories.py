class ProtectedContentRepository:
    """Protected reads/writes. Requires the internal database role."""

    def __init__(self, session: Session) -> None:
        self.session = session

    # --- blobs and fixtures ----------------------------------------------

    def put_blob(self, content: bytes, *, content_sha256: str, now: datetime) -> Blob:
        statement = (
            pg_insert(Blob)
            .values(
                content_sha256=content_sha256,
                content=content,
                size_bytes=len(content),
                created_at=now,
            )
            .on_conflict_do_nothing(index_elements=[Blob.content_sha256])
        )
        self.session.execute(statement)
        self.session.flush()
        blob = self.session.get(Blob, content_sha256)
        if blob is None:  # pragma: no cover - only reachable on a lost race
            raise RuntimeError("blob insert did not persist")
        return blob

    def upsert_fixture(
        self,
        *,
        question_version_id: uuid.UUID,
        path: str,
        mount: str,
        content: bytes,
        content_sha256: str,
        now: datetime,
    ) -> Fixture:
        self.put_blob(content, content_sha256=content_sha256, now=now)
        statement = (
            pg_insert(Fixture)
            .values(
                fixture_id=new_id(),
                question_version_id=question_version_id,
                path=path,
                mount=mount,
                content_sha256=content_sha256,
                size_bytes=len(content),
                created_at=now,
            )
            .on_conflict_do_update(
                index_elements=[Fixture.question_version_id, Fixture.path, Fixture.mount],
                set_={
                    "content_sha256": content_sha256,
                    "size_bytes": len(content),
                },
            )
        )
        self.session.execute(statement)
        self.session.flush()
        return self.get_fixture(question_version_id, path, mount)

    def get_fixture(
        self, question_version_id: uuid.UUID, path: str, mount: str
    ) -> Fixture:
        statement = select(Fixture).where(
            Fixture.question_version_id == question_version_id,
            Fixture.path == path,
            Fixture.mount == mount,
        )
        row = self.session.execute(statement).scalar_one()
        return row

    def list_fixtures(self, question_version_id: uuid.UUID) -> list[FixtureInternal]:
        statement = (
            select(Fixture)
            .where(Fixture.question_version_id == question_version_id)
            .order_by(Fixture.path, Fixture.mount)
        )
        return [
            FixtureInternal(
                fixture_id=row.fixture_id,
                question_version_id=row.question_version_id,
                path=row.path,
                mount=row.mount,  # type: ignore[arg-type]
                content_sha256=row.content_sha256,
                size_bytes=row.size_bytes,
            )
            for row in self.session.execute(statement).scalars()
        ]

    def delete_fixture(
        self, question_version_id: uuid.UUID, path: str, mount: str
    ) -> None:
        self.session.execute(
            delete(Fixture).where(
                Fixture.question_version_id == question_version_id,
                Fixture.path == path,
                Fixture.mount == mount,
            )
        )
        self.session.flush()

    # --- reference answers ------------------------------------------------

    def upsert_reference_answer(
        self,
        *,
        question_version_id: uuid.UUID,
        language: str,
        body: str,
        now: datetime,
    ) -> ReferenceAnswerInternal:
        statement = (
            pg_insert(ReferenceAnswer)
            .values(
                reference_answer_id=new_id(),
                question_version_id=question_version_id,
                language=language,
                body=body,
                created_at=now,
            )
            .on_conflict_do_update(
                index_elements=[
                    ReferenceAnswer.question_version_id,
                    ReferenceAnswer.language,
                ],
                set_={"body": body},
            )
            .returning(ReferenceAnswer.reference_answer_id)
        )
        reference_answer_id = self.session.execute(statement).scalar_one()
        self.session.flush()
        return ReferenceAnswerInternal(
            reference_answer_id=reference_answer_id,
            question_version_id=question_version_id,
            language=language,  # type: ignore[arg-type]
            body=body,
        )

    def list_reference_answers(
        self, question_version_id: uuid.UUID
    ) -> list[ReferenceAnswerInternal]:
        statement = (
            select(ReferenceAnswer)
            .where(ReferenceAnswer.question_version_id == question_version_id)
            .order_by(ReferenceAnswer.language)
        )
        return [
            ReferenceAnswerInternal(
                reference_answer_id=row.reference_answer_id,
                question_version_id=row.question_version_id,
                language=row.language,  # type: ignore[arg-type]
                body=row.body,
            )
            for row in self.session.execute(statement).scalars()
        ]

    def has_reference_answer(self, question_version_id: uuid.UUID) -> bool:
        count = self.session.execute(
            select(func.count())
            .select_from(ReferenceAnswer)
            .where(ReferenceAnswer.question_version_id == question_version_id)
        ).scalar_one()
        return bool(count)

    # --- test cases -------------------------------------------------------

    def ensure_test_suite(self, question_version_id: uuid.UUID, *, now: datetime) -> uuid.UUID:
        statement = (
            pg_insert(TestSuite)
            .values(
                test_suite_id=new_id(),
                question_version_id=question_version_id,
                created_at=now,
            )
            .on_conflict_do_nothing(index_elements=[TestSuite.question_version_id])
            .returning(TestSuite.test_suite_id)
        )
        created = self.session.execute(statement).scalar_one_or_none()
        if created is not None:
            self.session.flush()
            return created
        existing = self.session.execute(
            select(TestSuite.test_suite_id).where(
                TestSuite.question_version_id == question_version_id
            )
        ).scalar_one()
        return existing

    def replace_cases(
        self,
        *,
        question_version_id: uuid.UUID,
        suite_id: uuid.UUID,
        cases: Sequence[TestCaseInternal],
        now: datetime,
    ) -> None:
        self.session.execute(delete(TestCase).where(TestCase.test_suite_id == suite_id))
        for case in cases:
            self.session.add(
                TestCase(
                    test_case_id=case.case_id,
                    test_suite_id=suite_id,
                    question_version_id=question_version_id,
                    ordinal=case.ordinal,
                    name=case.name,
                    weight=case.weight,
                    visible_to_student=case.visible_to_student,
                    stdin=case.stdin,
                    args=list(case.args),
                    expected_stdout=case.expected_stdout,
                    expected_stderr=case.expected_stderr,
                    expected_exit_code=case.expected_exit_code,
                    created_at=now,
                )
            )
        self.session.flush()

    def list_cases(self, question_version_id: uuid.UUID) -> list[TestCaseInternal]:
        statement = (
            select(TestCase)
            .where(TestCase.question_version_id == question_version_id)
            .order_by(TestCase.ordinal)
        )
        return [
            TestCaseInternal(
                case_id=row.test_case_id,
                question_version_id=row.question_version_id,
                name=row.name,
                ordinal=row.ordinal,
                weight=row.weight,
                visible_to_student=row.visible_to_student,
                stdin=row.stdin,
                args=tuple(row.args or ()),
                expected_stdout=row.expected_stdout,
                expected_stderr=row.expected_stderr,
                expected_exit_code=row.expected_exit_code,
            )
            for row in self.session.execute(statement).scalars()
        ]


class DraftGenerationRepository:
    """Private generation records and the paid-call ledger (AI-FLOW-01A).

    Both live on the **protected** connection: the candidate may carry a reference answer
    and proposed hidden cases, and a record that holds protected content is never read on
    the least-privilege role -- not even for a status check.
    """

    def __init__(self, session: Session) -> None:
        self.session = session

    # --- candidates -------------------------------------------------------

    def create_generation(
        self,
        *,
        course_id: uuid.UUID,
        owner_subject: str,
        status: str,
        language: str,
        adapter_kind: str,
        provider: str,
        model: str,
        prompt_version: str,
        proposal: dict[str, Any] | None,
        warnings: list[dict[str, Any]],
        created_at: datetime,
        expires_at: datetime,
    ) -> QuestionDraftGeneration:
        row = QuestionDraftGeneration(
            generation_id=new_id(),
            course_id=course_id,
            owner_subject=owner_subject,
            status=status,
            language=language,
            adapter_kind=adapter_kind,
            provider=provider,
            model=model,
            prompt_version=prompt_version,
            proposal=proposal,
            warnings=list(warnings),
            created_at=created_at,
            expires_at=expires_at,
            accepted_question_version_id=None,
            accepted_at=None,
            discarded_at=None,
        )
        self.session.add(row)
        self.session.flush()
        return row

    def get_generation(self, generation_id: uuid.UUID) -> QuestionDraftGeneration | None:
        return self.session.get(QuestionDraftGeneration, generation_id)

    def delete_generation(self, row: QuestionDraftGeneration) -> None:
        """Purge an expired record. The ledger row is untouched: the call still happened."""
        self.session.delete(row)
        self.session.flush()

    def discard_generation(
        self, row: QuestionDraftGeneration, *, now: datetime
    ) -> QuestionDraftGeneration:
        """Drop the candidate content but keep the row, so "discarded" stays auditable."""
        row.proposal = None
        row.discarded_at = now
        self.session.flush()
        return row

    def accept_generation(
        self,
        row: QuestionDraftGeneration,
        *,
        question_version_id: uuid.UUID,
        now: datetime,
    ) -> QuestionDraftGeneration:
        """Record that the candidate became a version, and remove the candidate content.

        Called from inside the question-creation transaction: if the version write fails,
        this rolls back with it, so a generation can never be marked accepted for a version
        that does not exist.
        """
        row.proposal = None
        row.accepted_question_version_id = question_version_id
        row.accepted_at = now
        self.session.flush()
        return row

    # --- ledger -----------------------------------------------------------

    def record_usage(
        self,
        *,
        generation_id: uuid.UUID | None,
        course_id: uuid.UUID,
        owner_subject: str,
        provider: str,
        model: str,
        prompt_version: str,
        requested_at: datetime,
        duration_ms: int,
        status: str,
        error_category: str | None = None,
        prompt_tokens: int | None = None,
        completion_tokens: int | None = None,
        total_tokens: int | None = None,
    ) -> AIGenerationUsage:
        row = AIGenerationUsage(
            usage_id=new_id(),
            generation_id=generation_id,
            course_id=course_id,
            owner_subject=owner_subject,
            provider=provider,
            model=model,
            prompt_version=prompt_version,
            requested_at=requested_at,
            duration_ms=max(0, int(duration_ms)),
            status=status,
            error_category=error_category,
            prompt_tokens=prompt_tokens,
            completion_tokens=completion_tokens,
            total_tokens=total_tokens,
            accepted_question_version_id=None,
        )
        self.session.add(row)
        self.session.flush()
        return row

    def link_usage_to_version(
        self, generation_id: uuid.UUID, question_version_id: uuid.UUID
    ) -> None:
        """Copy the accepted version onto the ledger rows for this generation."""
        self.session.execute(
            update(AIGenerationUsage)
            .where(AIGenerationUsage.generation_id == generation_id)
            .values(accepted_question_version_id=question_version_id)
        )
        self.session.flush()

    def usage_since(self, owner_subject: str, since: datetime) -> list[AIGenerationUsage]:
        statement = (
            select(AIGenerationUsage)
            .where(
                AIGenerationUsage.owner_subject == owner_subject,
                AIGenerationUsage.requested_at >= since,
            )
            .order_by(AIGenerationUsage.requested_at)
        )
        return list(self.session.execute(statement).scalars())


class EventStoreRepository:
    """Inbox/outbox helpers used by the statistics consumer."""
    def __init__(self, session: Session) -> None:
        self.session = session

    def claim_event(self, values: dict[str, Any]) -> tuple[EventInbox | None, str]:
        """Insert the event unless ``event_id`` or ``evaluation_run_id`` was seen.

        Returns ``(row, outcome)`` with outcome in
        ``accepted | duplicate_event | duplicate_run | unknown_conflict``.
        """
        statement = (
            pg_insert(EventInbox)
            .values(**values)
            .on_conflict_do_nothing()
            .returning(EventInbox.event_id)
        )
        inserted = self.session.execute(statement).scalar_one_or_none()
        self.session.flush()
        if inserted is not None:
            return self.session.get(EventInbox, values["event_id"]), "accepted"
        existing = self.session.get(EventInbox, values["event_id"])
        if existing is not None:
            return existing, "duplicate_event"
        by_run = self.session.execute(
            select(EventInbox).where(
                EventInbox.evaluation_run_id == values["evaluation_run_id"]
            )
        ).scalar_one_or_none()
        if by_run is not None:
            return by_run, "duplicate_run"
        return None, "unknown_conflict"

    def mark_processed(self, event_id: uuid.UUID, now: datetime) -> None:
        row = self.session.get(EventInbox, event_id)
        if row is not None:
            row.processed_at = now
            self.session.flush()

    def inbox_rows_in_order(self) -> list[EventInbox]:
        statement = select(EventInbox).order_by(EventInbox.occurred_at, EventInbox.event_id)
        return list(self.session.execute(statement).scalars())

    def inbox_rows_in_window(
        self,
        *,
        version_ids: Sequence[uuid.UUID],
        from_at: datetime | None,
        to_at: datetime | None,
        page_size: int = WINDOW_PAGE_SIZE,
        max_rows: int = MAX_WINDOW_ROWS,
    ) -> Iterator[EventInbox]:
        """Page through one window in ``(occurred_at, event_id)`` order, bounded.

        The previous shape was ``list(...)`` over the whole window, which loaded every
        row of a 100k-event range into memory before aggregating a single counter. The
        scan is now a keyset walk with a fixed page size, so peak memory is one page
        regardless of window width, and the ``(question_version_id, occurred_at,
        event_id)`` index makes each page an index range read.

        ``max_rows`` is a stated limit, not a silent truncation: exceeding it raises, so
        a caller that asks for more than B3 will answer is told to narrow the window
        instead of receiving a quietly partial aggregate.
        """
        if not version_ids:
            return
        if page_size < 1:  # pragma: no cover - internal guard
            raise ValueError("page_size must be >= 1")

        cursor: tuple[datetime, uuid.UUID] | None = None
        scanned = 0
        while True:
            statement = select(EventInbox).where(
                EventInbox.question_version_id.in_(list(version_ids))
            )
            if from_at is not None:
                statement = statement.where(EventInbox.occurred_at >= from_at)
            if to_at is not None:
                statement = statement.where(EventInbox.occurred_at <= to_at)
            if cursor is not None:
                occurred_at, event_id = cursor
                statement = statement.where(
                    (EventInbox.occurred_at > occurred_at)
                    | (
                        (EventInbox.occurred_at == occurred_at)
                        & (EventInbox.event_id > event_id)
                    )
                )
            statement = (
                statement.order_by(EventInbox.occurred_at, EventInbox.event_id)
                .limit(page_size)
            )
            rows = list(self.session.execute(statement).scalars())
            if not rows:
                return
            scanned += len(rows)
            if scanned > max_rows:
                raise StatisticsWindowTooLarge(
                    "the requested window holds more than "
                    f"{max_rows} events; narrow `from`/`to` so the aggregate can be "
                    "computed from the event stream with a bounded scan"
                )
            yield from rows
            if len(rows) < page_size:
                return
            last = rows[-1]
            cursor = (last.occurred_at, last.event_id)

    def inbox_count(self) -> int:
        return int(
            self.session.execute(select(func.count()).select_from(EventInbox)).scalar_one()
        )

    def unprocessed_inbox_count(self) -> int:
        return int(
            self.session.execute(
                select(func.count())
                .select_from(EventInbox)
                .where(EventInbox.processed_at.is_(None))
            ).scalar_one()
        )

    def last_inbox_occurred_at(self) -> datetime | None:
        return self.session.execute(select(func.max(EventInbox.occurred_at))).scalar_one_or_none()

    # --- consumption counters ---------------------------------------------

    def record_consumption(
        self, outcome: str, *, occurred_at: datetime | None
    ) -> None:
        """Bump the counter for one delivery outcome.

        Called on every path, including the rejection path that never reaches
        ``event_inbox`` - which is the reason this table exists: without it, "no
        attempts yet" and "every attempt rejected" produce identical empty tables.
        """
        statement = pg_insert(ConsumptionCounter).values(
            outcome=outcome,
            delivery_count=1,
            last_occurred_at=occurred_at,
        )
        self.session.execute(
            statement.on_conflict_do_update(
                index_elements=[ConsumptionCounter.outcome],
                set_={
                    "delivery_count": ConsumptionCounter.delivery_count
                    + statement.excluded.delivery_count,
                    "last_occurred_at": func.greatest(
                        func.coalesce(
                            ConsumptionCounter.last_occurred_at, statement.excluded.last_occurred_at
                        ),
                        statement.excluded.last_occurred_at,
                    ),
                },
            )
        )
        self.session.flush()

    def consumption_counters(self) -> dict[str, ConsumptionCounter]:
        statement = select(ConsumptionCounter)
        return {
            row.outcome: row for row in self.session.execute(statement).scalars()
        }

    def clear_statistics(self) -> None:
        self.session.execute(delete(QuestionVersionFailureCategory))
        self.session.execute(delete(QuestionVersionScoreBucket))
        self.session.execute(delete(QuestionVersionStats))
        self.session.flush()
