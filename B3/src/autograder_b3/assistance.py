"""Authoring assistance: teacher-time advice on a draft question (``RQ-T-10``).

``ADR-0009`` decision 3 allows a model to help while the teacher is *writing* a
question, under three boundaries that this module exists to enforce:

1. **advice, never an edit** - nothing here writes to the bank, and the contract has no
   "apply" parameter;
2. **suggestions do not reach a student-visible position** - the request carries the
   stem the teacher is writing (which the teacher may show a model) and the response
   shape has no field that could carry a reference answer, a hidden case or an expected
   output. :func:`build_provider_payload` additionally asserts the **outgoing** payload
   against the protected vocabulary, so "no protected content was sent" is a checked
   fact rather than a comment;
3. **off by default** - with no provider configured the endpoint refuses with a message
   naming the missing configuration, and the authoring flow is fully usable without it.

The advice is advisory and is labelled as such. ``ADR-0009`` also records what this
cannot guarantee: a model could in principle paraphrase something it was shown. What is
structural is that B3 never *sends* protected content, never *stores* model output, and
never lets a suggestion become a write.
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from typing import Any, Literal, Protocol
from collections.abc import Mapping, Sequence

from .config import Settings
from .dto.internal import PROTECTED_FIELD_NAMES
from .errors import B3Error, Conflict
from .llm_client import LlmCallError, LlmConfig, complete_json, provider_name_for

Topic = Literal["quality", "comparison_policy", "wording", "difficulty", "coverage"]

#: Every topic the contract declares. Kept here so the prompt builder and the DTO
#: cannot drift apart.
TOPICS: tuple[Topic, ...] = (
    "quality",
    "comparison_policy",
    "wording",
    "difficulty",
    "coverage",
)

#: Bumped whenever the prompt text changes: the response carries it as provenance, so a
#: suggestion can always be traced to the instructions that produced it.
PROMPT_VERSION = "b3-authoring-v1"

#: Shown with every response. The contract requires a non-empty list and clients must
#: render it, because advice that looks like a verdict eventually gets treated as one.
DISCLAIMERS: tuple[str, ...] = (
    "Generated by a model, not by a grader. Non-deterministic and not a correctness proof.",
    "Does not execute the reference answer and does not verify that it produces the expected output.",
    "Advisory only: accepting a suggestion means you edit the draft yourself, and you remain the author of record.",
)

#: The instruction that describes the *output shape*. Static text, never interpolated with the
#: teacher's input: the draft view travels as data in the user message.
ADVICE_SYSTEM_PROMPT = (
    "You advise teachers on exercise design. You never produce "
    "expected outputs and you never claim a question is correct."
)


class AuthoringProviderError(B3Error):
    """The configured provider could not produce advice.

    A separate ``slug`` from ``Conflict`` so an operator can tell "not configured" from
    "configured but failing" in logs and in the response ``type``.
    """

    status = 502
    title = "Bad Gateway"
    slug = "authoring-provider-failed"


class AuthoringAssistanceUnavailable(Conflict):
    """No model provider is configured; the authoring flow stays usable without it."""

    slug = "authoring-assistance-unavailable"


@dataclass(frozen=True)
class Suggestion:
    topic: Topic
    message: str
    confidence: Literal["advisory"] = "advisory"


@dataclass(frozen=True)
class Provenance:
    provider: str
    model: str
    prompt_version: str = PROMPT_VERSION


@dataclass(frozen=True)
class AssistanceResult:
    suggestions: tuple[Suggestion, ...]
    provenance: Provenance | None
    disclaimers: tuple[str, ...] = DISCLAIMERS


class AuthoringProvider(Protocol):
    """Turns a de-identified draft view plus topics into advice."""

    name: str
    model: str

    def advise(
        self, *, payload: Mapping[str, Any], topics: Sequence[Topic], notes: str | None
    ) -> tuple[Suggestion, ...]: ...


def build_provider_payload(
    *,
    title: str,
    stem_markdown: str,
    language: str,
    adapter_kind: str,
    comparison: Mapping[str, Any],
    case_count: int,
    case_ordinals: tuple[int, ...],
    case_weights: tuple[float, ...],
    max_files: int,
    max_total_bytes: int,
    topics: Sequence[Topic],
    notes: str | None,
) -> dict[str, Any]:
    """Assemble the outgoing view of a draft. Public stem and *shape* metadata only.

    Deliberately absent: the reference answer, every case input, every expected output,
    every fixture body. The absence is asserted below rather than trusted, so a future
    edit that adds one of them fails loudly instead of quietly shipping a leak.
    """
    payload: dict[str, Any] = {
        "title": title,
        "stem_markdown": stem_markdown,
        "language": language,
        "adapter_kind": adapter_kind,
        "comparison": dict(comparison),
        "case_count": case_count,
        "case_ordinals": list(case_ordinals),
        "case_weights": list(case_weights),
        "max_files": max_files,
        "max_total_bytes": max_total_bytes,
        "topics": list(topics),
        "notes": notes,
    }
    assert_no_protected_keys(payload)
    return payload


def assert_no_protected_keys(payload: Any, *, path: str = "$") -> None:
    """Refuse to send anything whose key is in the protected vocabulary.

    The mirror image of ``api.serializers.assert_no_protected_keys``, pointed at the
    outbound model call instead of the response: the same vocabulary guards both ends.
    """
    if isinstance(payload, Mapping):
        for key, item in payload.items():
            if str(key).lower() in PROTECTED_FIELD_NAMES:
                raise AuthoringProviderError(
                    f"authoring payload would send protected field {path}.{key}"
                )
            assert_no_protected_keys(item, path=f"{path}.{key}")
    elif isinstance(payload, (list, tuple)):
        for index, item in enumerate(payload):
            assert_no_protected_keys(item, path=f"{path}[{index}]")


def build_prompt(*, payload: Mapping[str, Any], topics: Sequence[Topic]) -> str:
    """One instruction per requested topic, over an enumerable surface.

    The topic enum is what keeps the prompt surface closed: a caller cannot ask for
    "anything else", and every supported use is a documented one.
    """
    instructions = {
        "quality": "Point out anything that makes this question unfair or unanswerable.",
        "comparison_policy": (
            "Judge whether the declared comparison policy fits the expected output "
            "shape; say if it would misjudge a correct answer."
        ),
        "wording": "Point out ambiguous or underspecified wording in the stem.",
        "difficulty": "Estimate the difficulty for the intended course level and say why.",
        "coverage": (
            "Say which edge cases the declared case set looks like it is missing. "
            "Describe them in words; do not invent expected outputs."
        ),
    }
    lines = [
        f"Prompt {PROMPT_VERSION}. You are advising a teacher who is writing an exercise.",
        "Return a JSON object {\"suggestions\": [{\"topic\": ..., \"message\": ...}]}.",
        "Advise only. Do not rewrite the question, do not produce expected outputs, "
        "and do not claim the question is correct.",
        "",
        "Draft view (there is no reference answer, no hidden case and no expected "
        "output in this input; do not ask for them):",
        json.dumps(payload, ensure_ascii=False, sort_keys=True),
        "",
        "Requested advice:",
    ]
    lines.extend(f"- [{topic}] {instructions[topic]}" for topic in topics)
    return "\n".join(lines)


def parse_suggestions(
    raw: Any, *, topics: Sequence[Topic]
) -> tuple[Suggestion, ...]:
    """Validate a provider response into suggestions, or refuse the whole response.

    Two rules, both about keeping the surface closed:

    * only a requested topic is accepted - a provider cannot widen the enum;
    * a message that names a protected field, or that carries line breaks or control
      characters, is refused. Those are the shapes an echoed block of expected output
      arrives in, so refusing them removes the most plausible route by which a
      labellable leak could reach a teacher's screen labelled "advisory".
    """
    if not isinstance(raw, Mapping):
        raise AuthoringProviderError("the provider response is not a JSON object")
    entries = raw.get("suggestions")
    if not isinstance(entries, list):
        raise AuthoringProviderError("the provider response has no suggestions list")

    suggestions: list[Suggestion] = []
    for entry in entries:
        if not isinstance(entry, Mapping):
            raise AuthoringProviderError("a suggestion is not an object")
        topic = entry.get("topic")
        message = entry.get("message")
        if topic not in topics:
            raise AuthoringProviderError(
                f"the provider answered the topic {topic!r}, which was not requested"
            )
        if not isinstance(message, str) or not message.strip():
            raise AuthoringProviderError("a suggestion has an empty message")
        assert_no_protected_terms(message)
        suggestions.append(Suggestion(topic=topic, message=message.strip()))
    return tuple(suggestions)


def assert_no_protected_terms(message: str) -> None:
    lowered = message.lower()
    for name in PROTECTED_FIELD_NAMES:
        if name in lowered:
            raise AuthoringProviderError(
                "the provider response names a protected field; the response is refused "
                "rather than shown"
            )
    if any(character in message for character in "\r\n\t\x00"):
        raise AuthoringProviderError(
            "the provider response contains line breaks or control characters; a "
            "free-form block is refused rather than shown"
        )


@dataclass
@dataclass
class ResponsesAuthoringProvider:
    """One POST to the Responses endpoint, built by :mod:`autograder_b3.llm_client`.

    Deliberately not a dependency: the whole feature stays optional (ADR-0009 decision 4),
    and real network calls happen only when the deployment configured the provider.
    """

    config: LlmConfig

    @property
    def name(self) -> str:
        return self.config.provider_name

    @property
    def model(self) -> str:
        return self.config.model

    def advise(
        self, *, payload: Mapping[str, Any], topics: Sequence[Topic], notes: str | None
    ) -> tuple[Suggestion, ...]:
        try:
            document, _usage = complete_json(
                config=self.config,
                system_prompt=ADVICE_SYSTEM_PROMPT,
                user_prompt=build_prompt(payload=payload, topics=topics),
                max_output_tokens=2048,
            )
        except LlmCallError as error:
            raise AuthoringProviderError(
                f"the provider call failed ({error.category})"
            ) from error
        return parse_suggestions(document, topics=topics)


def provider_from_settings(settings: Settings) -> AuthoringProvider | None:
    """``None`` when the provider is off, which is the default (ADR-0009 decision 4)."""
    if not settings.llm_configured:
        return None
    assert settings.llm_base_url is not None
    assert settings.llm_model is not None
    return ResponsesAuthoringProvider(
        config=LlmConfig(
            base_url=settings.llm_base_url,
            model=settings.llm_model,
            api_key=settings.llm_api_key,
            timeout_seconds=settings.llm_timeout_seconds,
            provider_name=provider_name_for(settings.llm_base_url),
        )
    )


def require_enabled(settings: Settings) -> None:
    """Refuse with the missing configuration named, or return if assistance is on."""
    missing = settings.llm_missing_configuration
    if missing:
        raise AuthoringAssistanceUnavailable(
            "authoring assistance is not configured on this deployment; set "
            + " and ".join(missing)
            + " to enable it. The authoring flow is fully usable without it.",
            field="authoring",
        )
