"""评测编排与报告生成（`RQ-B-2-50/60` 的编排一侧 + `RQ-B-2-80`）。

| 模块 | 职责 |
|---|---|
| `ports` | 四个窄协议：`PackageSource` / `WorkspaceProvider` / `SecurityDecider` / `CaseRunner` |
| `store` | 运行、迁移史、逐用例证据、结果的持久化（含迁移校验器与"报告可读 ⇒ 结果已持久化"） |
| `progress` | 单调 `sequence` 取号、帧写入、终态帧唯一、可断线重连的读取器（SSE 数据来源） |
| `scoring` | 确定性评分 + 合计校验（无模型、无时间、无随机；`ADR-0005`） |
| `explanation` | 逐用例的**规则推导**解释文本（纯函数；模型输出永不进入） |
| `report` | 报告组装 + MAIN 契约校验 + `result_digest` + 学生/教师视图裁剪 |
| `orchestrator` | 流水线与运行状态迁移、并发闸门、outbox 事件、持久化先于报告 |

依赖方向：编排层只依赖 `ports` 里的协议；安全判定（`autograder_b2.security`）与沙箱执行
（`autograder_b2.runner`）的实现由集成方注入；静态检查直接调用已交付的
`autograder_b2.static.analyze_static`。

只使用、不修改：`autograder_b2.domain.*`（冻结类型）与 `autograder_b2.db.schema`（表映像）。
"""

