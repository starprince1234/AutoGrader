"""B2 runner 核心：沙箱策略、package 解析、三类 adapter、比较器、逐用例与批量执行。

本包是 `WP-B2-C` 的运行时核心（`RQ-B-2-50` 的"沙箱策略与可用性判定"+"逐用例执行与比较"），
并按 `MAIN/docs/architecture/unix-homework-evaluation.md` 扩展了 Unix 作业评测：

| 模块 | 职责 |
|---|---|
| `policy` | `RunnerPolicy`（冻结）、profile（default/workspace_prep/ssh_session）、规范化摘要、nsjail 配置生成、可用性前置判定、固定参数数组 |
| `package` | 契约形状 evaluation package → 内部不可变对象（含 `execution`/`segment`/`file_checks`/`ssh_check`，不合规即拒绝） |
| `adapters` | `stdin` / `file` / `callable` 三类执行形态 + B2 固定 harness/准备程序 + 工作区快照/差异 |
| `comparator` | `exact` / `ignore_trailing_whitespace` / `numeric_tolerance` / `ignored` 比较策略 |
| `cgroup` | cgroup v2 逐用例资源读数（`memory.peak`/`cpu.stat`/`pids.peak`）+ 运行期取样器 |
| `fixtures` | 受保护 input fixture 的 `FixtureProvider` 端口与工作区物化（逐字节校验） |
| `file_checks` | 运行后的工作区文件检查（lstat 普通文件、摘要、权限位） |
| `ssh_session` | SSH 会话驱动源码、严格 ssh argv 校验、证据解析（真实 sshd/ssh 客户端） |
| `run_case` | `run_case(package, submission) -> CaseEvidence`、进程树清理、失败归类、证据摘要 |
| `run_cases` | `run_cases(package, batch) -> tuple[CaseEvidence, ...]`（single_run 分段/文件检查、ssh_session） |

冻结签名与不变量见 [docs/architecture/interfaces.md](../../docs/architecture/interfaces.md) 第 5 节；
沙箱决策见 [docs/adr/ADR-0002-sandbox-execution-policy.md](../../docs/adr/ADR-0002-sandbox-execution-policy.md)。

**硬规则**：沙箱不可用 ⇒ 抛 `SandboxUnavailableError`，绝不退化为裸进程执行；启动只用固定参数数组。
"""

